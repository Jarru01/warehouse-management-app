-- Schema as Hibernate created it before Flyway was introduced.
-- Existing databases are baselined at this version and skip this script.

CREATE TABLE miestnost (
    typ  VARCHAR(31) NOT NULL,
    kluc VARCHAR(50) NOT NULL,
    CONSTRAINT miestnost_pkey PRIMARY KEY (kluc),
    CONSTRAINT miestnost_typ_check CHECK (typ IN ('MALY', 'VELKY'))
);

CREATE TABLE regal (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    kapacita       INTEGER     NOT NULL,
    miestnost_kluc VARCHAR(50) NOT NULL,
    CONSTRAINT regal_pkey PRIMARY KEY (id),
    CONSTRAINT regal_miestnost_fk FOREIGN KEY (miestnost_kluc) REFERENCES miestnost (kluc)
);

CREATE TABLE tovar (
    id                     VARCHAR(50)  NOT NULL,
    nazov                  VARCHAR(100) NOT NULL,
    odosielatel_id         VARCHAR(50)  NOT NULL,
    odosielatel_meno       VARCHAR(100) NOT NULL,
    odosielatel_priezvisko VARCHAR(100) NOT NULL,
    prijemca_id            VARCHAR(50)  NOT NULL,
    prijemca_meno          VARCHAR(100) NOT NULL,
    prijemca_priezvisko    VARCHAR(100) NOT NULL,
    slot                   INTEGER,
    vaha                   INTEGER      NOT NULL,
    regal_id               BIGINT,
    CONSTRAINT tovar_pkey PRIMARY KEY (id),
    CONSTRAINT tovar_regal_slot_uk UNIQUE (regal_id, slot),
    CONSTRAINT tovar_regal_fk FOREIGN KEY (regal_id) REFERENCES regal (id)
);

CREATE TABLE riaditel (
    id         VARCHAR(50)  NOT NULL,
    meno       VARCHAR(100) NOT NULL,
    priezvisko VARCHAR(100) NOT NULL,
    heslo_hash VARCHAR(100),
    CONSTRAINT riaditel_pkey PRIMARY KEY (id)
);

CREATE TABLE pracovnik (
    id              VARCHAR(50)  NOT NULL,
    meno            VARCHAR(100) NOT NULL,
    priezvisko      VARCHAR(100) NOT NULL,
    heslo_hash      VARCHAR(100),
    drzany_tovar_id VARCHAR(50),
    miestnost_kluc  VARCHAR(50),
    CONSTRAINT pracovnik_pkey PRIMARY KEY (id),
    CONSTRAINT pracovnik_drzany_tovar_uk UNIQUE (drzany_tovar_id),
    CONSTRAINT pracovnik_tovar_fk FOREIGN KEY (drzany_tovar_id) REFERENCES tovar (id),
    CONSTRAINT pracovnik_miestnost_fk FOREIGN KEY (miestnost_kluc) REFERENCES miestnost (kluc)
);

CREATE TABLE zakaznik (
    id         VARCHAR(50)  NOT NULL,
    meno       VARCHAR(100) NOT NULL,
    priezvisko VARCHAR(100) NOT NULL,
    heslo_hash VARCHAR(100),
    CONSTRAINT zakaznik_pkey PRIMARY KEY (id)
);
