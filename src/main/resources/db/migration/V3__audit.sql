-- Audit log of logins and every change made through the application.

CREATE TABLE audit_zaznam (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    cas        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    pouzivatel VARCHAR(80)                 NOT NULL,
    akcia      VARCHAR(50)                 NOT NULL,
    detail     VARCHAR(500),
    CONSTRAINT audit_zaznam_pkey PRIMARY KEY (id)
);

CREATE INDEX audit_zaznam_cas_idx ON audit_zaznam (cas DESC);
