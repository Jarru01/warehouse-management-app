-- Customer e-mail for password recovery, recovery tokens, login attempt
-- counters shared by all instances and Spring Session tables.

ALTER TABLE zakaznik
    ADD COLUMN email VARCHAR(254);

CREATE UNIQUE INDEX zakaznik_email_uk ON zakaznik (email);

CREATE TABLE obnova_hesla (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    zakaznik_id VARCHAR(50)                 NOT NULL,
    token_hash  VARCHAR(64)                 NOT NULL,
    vytvorene   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    plati_do    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    pouzite     BOOLEAN                     NOT NULL DEFAULT FALSE,
    CONSTRAINT obnova_hesla_pkey PRIMARY KEY (id),
    CONSTRAINT obnova_hesla_token_uk UNIQUE (token_hash),
    CONSTRAINT obnova_hesla_zakaznik_fk FOREIGN KEY (zakaznik_id) REFERENCES zakaznik (id) ON DELETE CASCADE
);

CREATE TABLE prihlasenie_pokusy (
    kluc     VARCHAR(120)                NOT NULL,
    pocet    INTEGER                     NOT NULL,
    zaciatok TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT prihlasenie_pokusy_pkey PRIMARY KEY (kluc)
);

-- Spring Session JDBC (official schema-postgresql.sql)
CREATE TABLE spring_session (
    primary_id            CHAR(36) NOT NULL,
    session_id            CHAR(36) NOT NULL,
    creation_time         BIGINT   NOT NULL,
    last_access_time      BIGINT   NOT NULL,
    max_inactive_interval INT      NOT NULL,
    expiry_time           BIGINT   NOT NULL,
    principal_name        VARCHAR(100),
    CONSTRAINT spring_session_pk PRIMARY KEY (primary_id)
);

CREATE UNIQUE INDEX spring_session_ix1 ON spring_session (session_id);
CREATE INDEX spring_session_ix2 ON spring_session (expiry_time);
CREATE INDEX spring_session_ix3 ON spring_session (principal_name);

CREATE TABLE spring_session_attributes (
    session_primary_id CHAR(36)     NOT NULL,
    attribute_name     VARCHAR(200) NOT NULL,
    attribute_bytes    BYTEA        NOT NULL,
    CONSTRAINT spring_session_attributes_pk PRIMARY KEY (session_primary_id, attribute_name),
    CONSTRAINT spring_session_attributes_fk FOREIGN KEY (session_primary_id)
        REFERENCES spring_session (primary_id) ON DELETE CASCADE
);
